import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

const html = await readFile('dist/index.html','utf8');
const patch = await readFile('dist/patch-v099-v0994-web.js','utf8');
const authority = await readFile('dist/patch-v100-v0994-authority.js','utf8');
const pkg = await readFile('package.json','utf8');
const sw = await readFile('apps/web/service-worker.js','utf8');
assert.match(pkg,/"version": "0\.99\.4"/);
assert.ok(!pkg.includes('apply-web-v0993.mjs'),'0.99.3 build layer must not run in 0.99.4');
assert.match(sw,/ct-web-0\.99\.4/);
assert.ok(html.includes('<script src="/patch-v099-v0994-web.js"></script>'));
assert.ok(html.includes('<script src="/patch-v100-v0994-authority.js"></script>'));
assert.ok(!html.includes('patch-v097-v0993-nav-pre.js'),'0.99.3 pre-gate must not be emitted');
assert.ok(!html.includes('patch-v098-v0993-web.js'),'0.99.3 final layer must not be emitted');
assert.doesNotThrow(()=>new vm.Script(patch));
assert.doesNotThrow(()=>new vm.Script(authority));
assert.match(patch,/cinetracker_profile_home_payload_v0994/);
assert.match(patch,/cinetracker_profile_remaining_v0994/);
assert.match(patch,/Juntando poeira/);
assert.match(patch,/Assistir a seguir \/ Watchlist/);
assert.match(patch,/CineTracker • v0\.99\.4/);
assert.ok(!/\['history'/.test(patch));
assert.ok(!authority.includes('MutationObserver'),'authority layer must not poll/reconcile DOM continuously');
assert.ok(!authority.includes('setInterval'),'authority layer must not run a permanent interval');
console.log('WEB_0994_OK runtime=single home=authoritative profile=remaining watchlist=full history-nav=removed');
