base as (
  select ((coalesce(wh.external_ids->>'baseline_watched_at_v0994','')::timestamptz) at time zone 'America/Sao_Paulo')::date d,
    sum(case when wh.item_type='episode' and coalesce(wh.external_ids->>'baseline_plays_v0994','') ~ '^[0-9]+$' then greatest(0,(wh.external_ids->>'baseline_plays_v0994')::int) else 0 end)::int episodes,
